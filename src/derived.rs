//! Generate a feature model from source-adapter facts and separately authored policies.
//!
//! This module never reads files or executes host code. Resolved source calls drive
//! effect propagation; a missing or unknown target is retained as an analysis gap.
use crate::{
    derived_model::*,
    model::{Diagnostic, Location},
};
use serde::{Deserialize, Serialize};
use serde_json::{json, Value};
use sha2::{Digest, Sha256};
use std::collections::{BTreeMap, BTreeSet, VecDeque};

pub const GENERATED_MARKER: &str = "// @generated by vitrifi source analysis";

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq, PartialOrd, Ord)]
pub struct UnknownCall {
    pub operation_id: String,
    pub expression: String,
    pub line: usize,
    pub column: usize,
    pub target: Option<String>,
    pub reason: String,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct DerivedOperation {
    pub source: SourceOperation,
    pub callees: Vec<String>,
    pub effective_effects: Vec<ResourceEffect>,
    pub reachable_unknowns: Vec<UnknownCall>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct DerivedFeature {
    pub name: String,
    pub purpose: String,
    pub roots: Vec<String>,
    /// Annotated roots and every reachable resolved source helper.
    pub operations: Vec<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "snake_case")]
pub enum PolicyStatus {
    Passed,
    Violated,
    Unknown,
    RuntimeRequired,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PolicyResult {
    pub operation_id: String,
    pub policy: SourcePolicy,
    pub status: PolicyStatus,
    pub message: String,
    /// Shortest resolved source-call path to an operation with the forbidden effect.
    pub effect_path: Vec<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct DerivedProgram {
    pub operations: BTreeMap<String, DerivedOperation>,
    pub features: BTreeMap<String, DerivedFeature>,
    pub diagnostics: Vec<Diagnostic>,
    pub policy_results: Vec<PolicyResult>,
    #[serde(default)]
    pub inventory: Option<SourceInventory>,
}

/// Keep adapter diagnostics global, but apply source policies only to operations
/// in the selected target graph. Policy result IDs retain the correct scope even
/// when multiple operations share a source line.
pub(crate) fn scoped_diagnostics(
    program: &DerivedProgram,
    selected: &BTreeSet<String>,
) -> Vec<Diagnostic> {
    let mut diagnostics: Vec<_> = program
        .diagnostics
        .iter()
        .filter(|diagnostic| diagnostic.code != "FORBIDDEN_EFFECT")
        .cloned()
        .collect();
    for result in &program.policy_results {
        if result.status == PolicyStatus::Violated && selected.contains(&result.operation_id) {
            if let Some(operation) = program.operations.get(&result.operation_id) {
                diagnostics.push(Diagnostic {
                    code: "FORBIDDEN_EFFECT".into(),
                    message: result.message.clone(),
                    location: at(&operation.source),
                });
            }
        }
    }
    diagnostics
}

fn at(source: &SourceOperation) -> Location {
    Location {
        path: source.path.clone(),
        line: source.line,
        column: 1,
    }
}
fn canonical<T: Serialize>(value: &T) -> String {
    serde_json::to_string(value).expect("source facts serialize")
}
fn short_hash(value: &str) -> String {
    format!("{:x}", Sha256::digest(value.as_bytes()))[..10].to_string()
}
fn valid_identifier(value: &str) -> bool {
    let mut chars = value.chars();
    chars
        .next()
        .is_some_and(|c| c.is_ascii_alphabetic() || c == '_')
        && chars.all(|c| c.is_ascii_alphanumeric() || c == '_')
}
fn valid_feature(value: &str) -> bool {
    !value.is_empty() && value.split('.').all(valid_identifier)
}
fn reachable(start: &[String], operations: &BTreeMap<String, DerivedOperation>) -> Vec<String> {
    let mut result = BTreeSet::new();
    let mut queue: VecDeque<_> = start.iter().cloned().collect();
    while let Some(id) = queue.pop_front() {
        if !result.insert(id.clone()) {
            continue;
        }
        if let Some(operation) = operations.get(&id) {
            queue.extend(operation.callees.iter().cloned());
        }
    }
    result.into_iter().collect()
}
fn effect_path(
    start: &str,
    effect: &ResourceEffect,
    operations: &BTreeMap<String, DerivedOperation>,
) -> Vec<String> {
    let mut visited = BTreeSet::new();
    let mut queue = VecDeque::from([vec![start.to_string()]]);
    while let Some(path) = queue.pop_front() {
        let id = path.last().unwrap();
        if !visited.insert(id.clone()) {
            continue;
        }
        let Some(operation) = operations.get(id) else {
            continue;
        };
        if operation.source.direct_effects.contains(effect) {
            return path;
        }
        for callee in &operation.callees {
            let mut next = path.clone();
            next.push(callee.clone());
            queue.push_back(next);
        }
    }
    Vec::new()
}

pub fn build(mut analysis: SourceAnalysis) -> DerivedProgram {
    let mut diagnostics = analysis.diagnostics;
    // Canonicalize adapter ordering. Parameter order is part of a signature.
    for source in &mut analysis.operations {
        source.calls.sort_by_key(canonical);
        source.calls.dedup();
        source.direct_effects.sort();
        source.direct_effects.dedup();
        source.policies.sort_by_key(canonical);
        source.policies.dedup();
    }
    analysis.operations.sort_by(|a, b| {
        a.id.cmp(&b.id)
            .then_with(|| canonical(a).cmp(&canonical(b)))
    });
    let mut operations = BTreeMap::new();
    for source in analysis.operations {
        if operations.contains_key(&source.id) {
            diagnostics.push(Diagnostic {
                code: "DUPLICATE_SOURCE_OPERATION".into(),
                message: format!(
                    "Source adapter produced duplicate operation identity {}",
                    source.id
                ),
                location: at(&source),
            });
            continue;
        }
        if let Some(marker) = &source.feature {
            if !valid_feature(&marker.name) {
                diagnostics.push(Diagnostic {
                    code: "INVALID_FEATURE_NAME".into(),
                    message: format!(
                        "Feature marker {:?} must be a dotted sequence of ASCII identifiers",
                        marker.name
                    ),
                    location: at(&source),
                });
            }
        }
        operations.insert(
            source.id.clone(),
            DerivedOperation {
                effective_effects: source.direct_effects.clone(),
                source,
                callees: vec![],
                reachable_unknowns: vec![],
            },
        );
    }
    let ids: BTreeSet<_> = operations.keys().cloned().collect();
    let mut parents: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
    let mut effects: BTreeMap<String, BTreeSet<ResourceEffect>> = BTreeMap::new();
    let mut unknowns: BTreeMap<String, BTreeSet<UnknownCall>> = BTreeMap::new();
    for (id, operation) in &mut operations {
        let mut callees = BTreeSet::new();
        let mut gaps = BTreeSet::new();
        for call in &operation.source.calls {
            match (&call.resolution, &call.target) {
                (CallResolution::Resolved, Some(target)) if ids.contains(target) => {
                    callees.insert(target.clone());
                    parents
                        .entry(target.clone())
                        .or_default()
                        .insert(id.clone());
                }
                (CallResolution::Intrinsic, _) => (),
                _ => {
                    let reason = if call.resolution == CallResolution::Resolved {
                        format!(
                            "Resolved target {} is absent from this source analysis; {}",
                            call.target.as_deref().unwrap_or("<missing>"),
                            call.reason
                        )
                    } else {
                        call.reason.clone()
                    };
                    gaps.insert(UnknownCall {
                        operation_id: id.clone(),
                        expression: call.expression.clone(),
                        line: call.line,
                        column: call.column,
                        target: call.target.clone(),
                        reason,
                    });
                }
            }
        }
        operation.callees = callees.into_iter().collect();
        effects.insert(
            id.clone(),
            operation.source.direct_effects.iter().cloned().collect(),
        );
        unknowns.insert(id.clone(), gaps);
    }
    // Monotone worklist reaches a fixed point even for recursive source graphs.
    let mut queue: VecDeque<_> = ids.iter().cloned().collect();
    let mut queued = ids.clone();
    while let Some(id) = queue.pop_front() {
        queued.remove(&id);
        let child_effects = effects[&id].clone();
        let child_unknowns = unknowns[&id].clone();
        for parent in parents.get(&id).into_iter().flatten() {
            let parent_effects = effects.get_mut(parent).unwrap();
            let effect_count = parent_effects.len();
            parent_effects.extend(child_effects.iter().cloned());
            let parent_unknowns = unknowns.get_mut(parent).unwrap();
            let unknown_count = parent_unknowns.len();
            parent_unknowns.extend(child_unknowns.iter().cloned());
            if (parent_effects.len() != effect_count || parent_unknowns.len() != unknown_count)
                && queued.insert(parent.clone())
            {
                queue.push_back(parent.clone());
            }
        }
    }
    for (id, operation) in &mut operations {
        operation.effective_effects = effects.remove(id).unwrap().into_iter().collect();
        operation.reachable_unknowns = unknowns.remove(id).unwrap().into_iter().collect();
    }
    let mut roots: BTreeMap<String, Vec<String>> = BTreeMap::new();
    let mut purposes: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
    for (id, operation) in &operations {
        if let Some(marker) = &operation.source.feature {
            roots
                .entry(marker.name.clone())
                .or_default()
                .push(id.clone());
            if !marker.purpose.is_empty() {
                purposes
                    .entry(marker.name.clone())
                    .or_default()
                    .insert(marker.purpose.clone());
            }
        }
    }
    let features = roots
        .into_iter()
        .map(|(name, roots)| {
            let feature = DerivedFeature {
                operations: reachable(&roots, &operations),
                roots,
                purpose: purposes
                    .remove(&name)
                    .unwrap_or_default()
                    .into_iter()
                    .collect::<Vec<_>>()
                    .join("\n"),
                name: name.clone(),
            };
            (name, feature)
        })
        .collect();
    let mut policy_results = Vec::new();
    for (id, operation) in &operations {
        for policy in &operation.source.policies {
            let (status, message, path) = match policy {
                SourcePolicy::Forbid { effect } => {
                    if operation.effective_effects.contains(effect) {
                        let path = effect_path(id, effect, &operations);
                        (PolicyStatus::Violated, format!("{} forbids {} {}, but source analysis reaches that effect through {}", id, effect.action, effect.resource, path.join(" → ")), path)
                    } else if !operation.reachable_unknowns.is_empty() {
                        (PolicyStatus::Unknown, format!("Cannot establish the prohibition of {} {}: {} reachable call site(s) have unknown effects", effect.action, effect.resource, operation.reachable_unknowns.len()), Vec::new())
                    } else {
                        (PolicyStatus::Passed, format!("No {} {} effect is reachable within this adapter's analyzed source graph and modeled boundaries", effect.action, effect.resource), Vec::new())
                    }
                }
                SourcePolicy::NoEffectOnError { effect } => (PolicyStatus::RuntimeRequired,
                    format!("No {} {} on error requires scenario-linked runtime evidence; static reachability does not establish error-path behavior", effect.action, effect.resource), Vec::new()),
            };
            if status == PolicyStatus::Violated {
                diagnostics.push(Diagnostic {
                    code: "FORBIDDEN_EFFECT".into(),
                    message: message.clone(),
                    location: at(&operation.source),
                });
            }
            policy_results.push(PolicyResult {
                operation_id: id.clone(),
                policy: policy.clone(),
                status,
                message,
                effect_path: path,
            });
        }
    }
    diagnostics.sort_by(|a, b| {
        (
            &a.location.path,
            a.location.line,
            a.location.column,
            &a.code,
            &a.message,
        )
            .cmp(&(
                &b.location.path,
                b.location.line,
                b.location.column,
                &b.code,
                &b.message,
            ))
    });
    diagnostics.dedup();
    DerivedProgram {
        operations,
        features,
        diagnostics,
        policy_results,
        inventory: analysis.inventory,
    }
}

fn one_line(value: &str) -> String {
    value.split_whitespace().collect::<Vec<_>>().join(" ")
}
fn quote(value: &str) -> String {
    serde_json::to_string(value).unwrap()
}
fn identifier(value: &str, fallback: &str) -> String {
    let mut result = String::new();
    for c in value.chars() {
        result.push(if c.is_ascii_alphanumeric() || c == '_' {
            c
        } else {
            '_'
        });
    }
    if result.is_empty() {
        result.push_str(fallback);
    }
    if result.as_bytes()[0].is_ascii_digit() {
        result.insert(0, '_');
    }
    if matches!(
        result.as_str(),
        "String"
            | "Int"
            | "Bool"
            | "Unit"
            | "Any"
            | "List"
            | "Option"
            | "Result"
            | "use"
            | "as"
            | "feature"
            | "export"
            | "purpose"
            | "question"
            | "type"
            | "resource"
            | "requirement"
            | "boundary"
            | "allows"
            | "operation"
            | "check"
            | "bind"
            | "symbol"
            | "effects"
            | "requires"
            | "ensures"
            | "calls"
            | "run"
            | "cwd"
            | "covers"
            | "timeout"
            | "read"
            | "write"
            | "network"
            | "emit"
    ) {
        result.insert_str(0, "decl_");
    }
    result
}
fn method_name(source: &SourceOperation) -> String {
    let base = source.symbol.split('(').next().unwrap_or(&source.symbol);
    let name = if let Some(owner) = base.strip_suffix(".<init>") {
        format!("{}_new", owner.rsplit(['.', '$']).next().unwrap_or(owner))
    } else {
        base.rsplit(['.', '#', ':', '$'])
            .next()
            .unwrap_or(base)
            .to_string()
    };
    if let Some((_, suffix)) = source.symbol.rsplit_once(')') {
        if let Some(ordinals) = suffix.strip_prefix("$rowMapper") {
            let ordinals: Vec<_> = ordinals.split("$rowMapper").collect();
            if ordinals.iter().all(|ordinal| {
                !ordinal.is_empty()
                    && *ordinal != "0"
                    && ordinal.bytes().all(|digit| digit.is_ascii_digit())
            }) {
                let callbacks = ordinals
                    .iter()
                    .map(|ordinal| format!("rowMapper{ordinal}"))
                    .collect::<Vec<_>>()
                    .join("_");
                return identifier(&format!("{name}_{callbacks}"), "rowMapper");
            }
        }
    }
    if source.symbol.contains("$lambda@") {
        identifier(&format!("{name}_rowMapper"), "rowMapper")
    } else {
        identifier(&name, "operation")
    }
}
fn known_type(annotation: &str) -> Option<&'static str> {
    match annotation.trim() {
        "void" | "Unit" | "()" => Some("Unit"),
        "boolean" | "bool" | "java.lang.Boolean" | "Bool" => Some("Bool"),
        "byte" | "short" | "int" | "long" | "java.lang.Byte" | "java.lang.Short"
        | "java.lang.Integer" | "java.lang.Long" | "Int" => Some("Int"),
        "String" | "java.lang.String" | "str" => Some("String"),
        "" | "Any" => Some("Any"),
        _ => None,
    }
}
fn native_type_name(annotation: &str) -> String {
    // Keep qualification in the native signature; the review surface uses the
    // simple name. Generic arguments and arrays remain recognizable opaque types.
    let mut pieces = annotation
        .split(|c: char| !c.is_alphanumeric() && !matches!(c, '_' | '$' | '.'))
        .filter(|part| !part.is_empty())
        .map(|part| part.rsplit('.').next().unwrap_or(part))
        .collect::<Vec<_>>();
    for _ in annotation.matches("[]") {
        pieces.push("Array");
    }
    identifier(
        &pieces.join("_").chars().take(80).collect::<String>(),
        "Value",
    )
}

/// Operations, resources, and types share a namespace. Only actual collisions
/// need a suffix; reserve natural names before allocating hashed alternatives.
fn declaration_names(candidates: BTreeMap<String, String>) -> BTreeMap<String, String> {
    let mut counts = BTreeMap::<String, usize>::new();
    for base in candidates.values() {
        *counts.entry(base.clone()).or_default() += 1;
    }
    let mut used: BTreeSet<_> = counts.keys().cloned().collect();
    candidates
        .into_iter()
        .map(|(identity, base)| {
            let name = if counts[&base] == 1 {
                base
            } else {
                let mut name = format!("{base}_{}", short_hash(&identity));
                while !used.insert(name.clone()) {
                    name.push('_');
                }
                name
            };
            (identity, name)
        })
        .collect()
}
fn relative_binding(output_path: &str, source_path: &str) -> Result<String, String> {
    fn parts(path: &str) -> Result<Vec<&str>, String> {
        if path.starts_with('/') || path.contains('\\') {
            return Err("Rendering requires repository-relative paths with '/' separators".into());
        }
        let mut result = Vec::new();
        for piece in path.split('/') {
            match piece {
                "" | "." => (),
                ".." => {
                    if result.pop().is_none() {
                        return Err("Path escapes repository root".into());
                    }
                }
                _ => result.push(piece),
            }
        }
        Ok(result)
    }
    let mut output = parts(output_path)?;
    if output.pop().is_none() {
        return Err("An output filename is required".into());
    }
    let source = parts(source_path)?;
    if source.is_empty() {
        return Err("A source filename is required".into());
    }
    let shared = output
        .iter()
        .zip(&source)
        .take_while(|(a, b)| a == b)
        .count();
    let relative = std::iter::repeat_n("..", output.len() - shared)
        .chain(source[shared..].iter().copied())
        .collect::<Vec<_>>()
        .join("/");
    Ok(if relative.starts_with("../") {
        relative
    } else {
        format!("./{relative}")
    })
}

/// Render one deterministic, generated feature view. The output path is relative
/// to the same repository root as source paths. New source-analysis checking is
/// authoritative; legacy handwritten binding rules are not used for this view.
pub fn render(
    program: &DerivedProgram,
    feature_name: &str,
    output_path: &str,
) -> Result<String, String> {
    let feature = program
        .features
        .get(feature_name)
        .ok_or_else(|| format!("Unknown generated feature {feature_name}"))?;
    if !valid_feature(feature_name) {
        return Err(format!("Invalid .vitrifi feature name {feature_name:?}"));
    }
    let mut candidates = BTreeMap::new();
    for id in &feature.operations {
        candidates.insert(
            format!("operation:{id}"),
            method_name(&program.operations[id].source),
        );
    }
    let mut resources = BTreeMap::<String, String>::new();
    let mut types = BTreeMap::<String, String>::new();
    for id in &feature.operations {
        let op = &program.operations[id];
        for effect in &op.effective_effects {
            resources.entry(effect.resource.clone()).or_insert_with(|| {
                identifier(
                    effect
                        .resource
                        .rsplit('.')
                        .next()
                        .unwrap_or(&effect.resource),
                    "State",
                )
            });
        }
        for ty in op
            .source
            .parameters
            .iter()
            .map(|p| &p.annotation)
            .chain(std::iter::once(&op.source.returns))
        {
            if known_type(ty).is_none() {
                types
                    .entry(ty.clone())
                    .or_insert_with(|| native_type_name(ty));
            }
        }
    }
    for (resource, base) in &resources {
        candidates.insert(format!("resource:{resource}"), base.clone());
    }
    for (native, base) in &types {
        candidates.insert(format!("type:{native}"), base.clone());
    }
    let allocated = declaration_names(candidates);
    let names: BTreeMap<_, _> = feature
        .operations
        .iter()
        .map(|id| (id.clone(), allocated[&format!("operation:{id}")].clone()))
        .collect();
    for (resource, name) in &mut resources {
        *name = allocated[&format!("resource:{resource}")].clone();
    }
    for (native, name) in &mut types {
        *name = allocated[&format!("type:{native}")].clone();
    }
    let mut lines=vec![GENERATED_MARKER.into(),
        "// Regenerate from source. Edits to this view do not change authored source policies.".into(),
        "// Checked by the source-analysis workflow; native overload identities may not match legacy handwritten bindings.".into(),
        "// Adapter facts and propagated effects describe the supported analysis scope, not a proof of all host behavior.".into(),
        format!("feature {feature_name} {{"),format!("  purpose {};",quote(&feature.purpose))];
    for (native, name) in &types {
        lines.push(format!("  // Native type: {}", one_line(native)));
        lines.push(format!("  export type {name};"));
    }
    for (resource, name) in &resources {
        lines.push(format!("  // Source resource: {}", quote(resource)));
        lines.push(format!("  export resource {name};"));
    }
    let mut gaps = BTreeSet::new();
    for id in &feature.operations {
        let operation = &program.operations[id];
        let source = &operation.source;
        gaps.extend(operation.reachable_unknowns.iter().cloned());
        let native = |ty: &str| {
            known_type(ty)
                .map(str::to_string)
                .unwrap_or_else(|| types[ty].clone())
        };
        let mut parameters = Vec::new();
        let mut param_names = BTreeSet::new();
        for (index, p) in source.parameters.iter().enumerate() {
            let mut name = identifier(&p.name, &format!("arg{index}"));
            while !param_names.insert(name.clone()) {
                name.push('_');
            }
            parameters.push(format!("{name}: {}", native(&p.annotation)));
        }
        lines.push(String::new());
        lines.push(format!("  // Source identity: {}", quote(id)));
        lines.push(format!(
            "  // Source: {}:{}",
            one_line(&source.path),
            source.line
        ));
        lines.push(format!(
            "  // Native signature: {}",
            one_line(&source.signature)
        ));
        let exported = if feature.roots.contains(id) {
            "export "
        } else {
            ""
        };
        lines.push(format!(
            "  {exported}operation {}({}) -> {} {{",
            names[id],
            parameters.join(", "),
            native(&source.returns)
        ));
        if !matches!(
            source.language.as_str(),
            "java" | "python" | "ruby" | "javascript" | "typescript"
        ) {
            return Err(format!("Unsupported binding language {}", source.language));
        }
        lines.push(format!(
            "    bind {} {} symbol {};",
            source.language,
            quote(&relative_binding(output_path, &source.path)?),
            quote(&source.symbol)
        ));
        if !source.direct_effects.is_empty() {
            lines.push(format!(
                "    // Direct source-adapter effects: {}",
                one_line(&canonical(&source.direct_effects))
            ));
        }
        let mut effects = Vec::new();
        for effect in &operation.effective_effects {
            if matches!(
                effect.action.as_str(),
                "read" | "write" | "network" | "emit"
            ) {
                effects.push(format!("{} {}", effect.action, resources[&effect.resource]));
            } else {
                lines.push(format!(
                    "    // Effect action outside this view's grammar: {}",
                    canonical(effect)
                ));
            }
        }
        lines.push(format!("    effects [{}];", effects.join(", ")));
        lines.push(format!(
            "    calls [{}];",
            operation
                .callees
                .iter()
                .map(|c| names[c].clone())
                .collect::<Vec<_>>()
                .join(", ")
        ));
        for result in program
            .policy_results
            .iter()
            .filter(|r| r.operation_id == *id)
        {
            lines.push(format!(
                "    // Authored source policy: {}",
                canonical(&result.policy)
            ));
            lines.push(format!(
                "    // Policy result: {} — {}",
                canonical(&result.status),
                one_line(&result.message)
            ));
        }
        lines.push("  }".into());
    }
    for gap in gaps {
        lines.push(format!(
            "  question {};",
            quote(&format!(
                "Analysis gap at {}:{}:{}: {} — {}",
                gap.operation_id, gap.line, gap.column, gap.expression, gap.reason
            ))
        ));
    }
    lines.push("}".into());
    Ok(lines.join("\n") + "\n")
}

fn semantic_unknown(gap: &UnknownCall) -> Value {
    json!({"operation_id":gap.operation_id,"expression":one_line(&gap.expression),"target":gap.target,"reason":one_line(&gap.reason)})
}
fn sorted_values(values: impl Iterator<Item = Value>) -> Vec<Value> {
    let mut values: Vec<_> = values.collect();
    values.sort_by_key(canonical);
    values.dedup();
    values
}
/// Stable review facts. Source positions and generated comments are intentionally
/// absent; native signatures, resolution gaps, effects and authored policies remain.
pub fn facts(program: &DerivedProgram) -> BTreeMap<String, Value> {
    let mut result = BTreeMap::new();
    for (name, feature) in &program.features {
        result.insert(format!("feature {name}"),json!({"name":name,"purpose":feature.purpose,"roots":feature.roots,"operations":feature.operations}));
    }
    for (id, operation) in &program.operations {
        let source = &operation.source;
        let calls=sorted_values(source.calls.iter().map(|call|json!({"expression":one_line(&call.expression),"target":call.target,"source_owner":call.source_owner,"resolution":call.resolution,"reason":one_line(&call.reason)})));
        let unknowns = sorted_values(operation.reachable_unknowns.iter().map(semantic_unknown));
        result.insert(format!("operation {id}"),json!({"path":source.path,"symbol":source.symbol,"language":source.language,
            "native_signature":one_line(&source.signature),"parameters":source.parameters,"returns":source.returns,
            "feature":source.feature,"calls":calls,"direct_effects":source.direct_effects,
            "effective_effects":operation.effective_effects,"reachable_unknowns":unknowns}));
        if !source.policies.is_empty() {
            result.insert(format!("policy {id}"), json!(source.policies));
        }
    }
    result
}

