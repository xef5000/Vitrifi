//! A closed, executable workflow core. Java leaves remain separately analyzed.
use crate::{
    derived::DerivedProgram,
    derived_model::ResourceEffect,
    model::{Diagnostic, Location},
    target::{self, Kind, TargetParameter, TargetResource, Token},
};
use serde::{Deserialize, Serialize};
use std::collections::{BTreeMap, BTreeSet};

pub const GENERATED_MARKER: &str = "// @generated by vitrifi workflow compiler";
pub const SEMANTICS: &str = "vitrifi.workflow/1";

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Workflow {
    pub path: String,
    pub feature: String,
    pub purpose: String,
    pub emit: String,
    pub actions: String,
    pub resources: Vec<TargetResource>,
    pub leaves: Vec<Leaf>,
    pub operations: Vec<Operation>,
    pub location: Location,
}
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Leaf {
    pub name: String,
    pub parameters: Vec<TargetParameter>,
    pub returns: String,
    pub binding: String,
    pub effects: Vec<ResourceEffect>,
    pub location: Location,
}
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Operation {
    pub name: String,
    pub parameters: Vec<TargetParameter>,
    pub returns: String,
    pub effects: Vec<ResourceEffect>,
    pub no_effect_on_rejection: Vec<ResourceEffect>,
    pub body: Vec<Statement>,
    pub location: Location,
}
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "kind", content = "value", rename_all = "snake_case")]
pub enum Value {
    Ref(String),
    Text(String),
    Bool(bool),
}
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Call {
    pub action: String,
    pub arguments: Vec<Value>,
}
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum Statement {
    Let {
        name: String,
        call: Call,
        location: Location,
    },
    Do {
        call: Call,
        location: Location,
    },
    If {
        condition: Value,
        yes: Vec<Statement>,
        no: Vec<Statement>,
        location: Location,
    },
    Return {
        value: Value,
        location: Location,
    },
    Reject {
        message: String,
        location: Location,
    },
}
fn error(at: &Location, code: &str, message: impl Into<String>) -> Diagnostic {
    Diagnostic {
        code: code.into(),
        message: message.into(),
        location: at.clone(),
    }
}

struct Parser {
    tokens: Vec<Token>,
    index: usize,
}
impl Parser {
    fn at(&self) -> &Location {
        &self.tokens[self.index].at
    }
    fn kind(&self) -> &Kind {
        &self.tokens[self.index].kind
    }
    fn take(&mut self) -> Kind {
        let value = self.kind().clone();
        if value != Kind::End {
            self.index += 1;
        }
        value
    }
    fn fail(&self, message: impl Into<String>) -> Diagnostic {
        error(self.at(), "WORKFLOW_PARSE", message)
    }
    fn eat(&mut self, c: char) -> bool {
        if self.kind() == &Kind::Punct(c) {
            self.index += 1;
            true
        } else {
            false
        }
    }
    fn punct(&mut self, c: char) -> Result<(), Diagnostic> {
        if self.eat(c) {
            Ok(())
        } else {
            Err(self.fail(format!("Expected '{c}'")))
        }
    }
    fn word(&mut self) -> Result<String, Diagnostic> {
        if let Kind::Word(value) = self.take() {
            Ok(value)
        } else {
            Err(self.fail("Expected identifier"))
        }
    }
    fn keyword(&mut self, expected: &str) -> Result<(), Diagnostic> {
        if self.word()? == expected {
            Ok(())
        } else {
            Err(self.fail(format!("Expected '{expected}'")))
        }
    }
    fn string(&mut self) -> Result<String, Diagnostic> {
        if let Kind::String(value) = self.take() {
            Ok(value)
        } else {
            Err(self.fail("Expected quoted string"))
        }
    }
    fn parameters(&mut self) -> Result<Vec<TargetParameter>, Diagnostic> {
        self.punct('(')?;
        let mut result = Vec::new();
        if !self.eat(')') {
            loop {
                let name = self.word()?;
                self.punct(':')?;
                result.push(TargetParameter {
                    name,
                    native_type: self.string()?,
                });
                if self.eat(')') {
                    break;
                }
                self.punct(',')?;
            }
        }
        Ok(result)
    }
    fn returns(&mut self) -> Result<String, Diagnostic> {
        if self.take() != Kind::Arrow {
            return Err(self.fail("Expected '->'"));
        }
        self.string()
    }
    fn effects(&mut self) -> Result<Vec<ResourceEffect>, Diagnostic> {
        self.punct('[')?;
        let mut result = Vec::new();
        if !self.eat(']') {
            loop {
                result.push(ResourceEffect {
                    action: self.word()?,
                    resource: self.word()?,
                });
                if self.eat(']') {
                    break;
                }
                self.punct(',')?;
            }
        }
        self.punct(';')?;
        Ok(result)
    }
    fn value(&mut self) -> Result<Value, Diagnostic> {
        match self.take() {
            Kind::String(v) => Ok(Value::Text(v)),
            Kind::Word(v) if v == "true" || v == "false" => Ok(Value::Bool(v == "true")),
            Kind::Word(v) => Ok(Value::Ref(v)),
            _ => Err(self.fail("Expected a bound value, string, or boolean")),
        }
    }
    fn call(&mut self) -> Result<Call, Diagnostic> {
        self.keyword("call")?;
        let action = self.word()?;
        self.punct('(')?;
        let mut arguments = Vec::new();
        if !self.eat(')') {
            loop {
                arguments.push(self.value()?);
                if self.eat(')') {
                    break;
                }
                self.punct(',')?;
            }
        }
        self.punct(';')?;
        Ok(Call { action, arguments })
    }
    fn block(&mut self, depth: usize) -> Result<Vec<Statement>, Diagnostic> {
        if depth > 64 {
            return Err(self.fail("Workflow nesting exceeds 64 blocks"));
        }
        self.punct('{')?;
        let mut result = Vec::new();
        while !self.eat('}') {
            result.push(self.statement(depth)?);
        }
        Ok(result)
    }
    fn statement(&mut self, depth: usize) -> Result<Statement, Diagnostic> {
        let location = self.at().clone();
        Ok(match self.word()?.as_str() {
            "let" => {
                let name = self.word()?;
                self.punct('=')?;
                Statement::Let {
                    name,
                    call: self.call()?,
                    location,
                }
            }
            "do" => Statement::Do {
                call: self.call()?,
                location,
            },
            "if" => {
                let condition = self.value()?;
                let yes = self.block(depth + 1)?;
                self.keyword("else")?;
                let no = self.block(depth + 1)?;
                Statement::If {
                    condition,
                    yes,
                    no,
                    location,
                }
            }
            "return" => {
                let value = self.value()?;
                self.punct(';')?;
                Statement::Return { value, location }
            }
            "reject" => {
                let message = self.string()?;
                self.punct(';')?;
                Statement::Reject { message, location }
            }
            other => {
                return Err(self.fail(format!(
                "Unknown workflow statement '{other}'; expected let, do, if/else, return, or reject"
            )))
            }
        })
    }
    fn workflow(&mut self, path: &str) -> Result<Workflow, Diagnostic> {
        let location = self.at().clone();
        self.keyword("workflow")?;
        self.keyword("feature")?;
        let mut feature = self.word()?;
        while self.eat('.') {
            feature.push('.');
            feature.push_str(&self.word()?);
        }
        self.punct('{')?;
        let (mut purpose, mut emit, mut actions) = (None, None, None);
        let mut fields = BTreeSet::new();
        let (mut resources, mut leaves, mut operations) = (Vec::new(), Vec::new(), Vec::new());
        while !self.eat('}') {
            let at = self.at().clone();
            let field = self.word()?;
            match field.as_str() {
                "purpose" | "emit" | "actions" => {
                    if !fields.insert(field.clone()) {
                        return Err(self.fail(format!("Duplicate {field}")));
                    }
                    if field != "purpose" {
                        self.keyword("java")?;
                    }
                    let value = self.string()?;
                    self.punct(';')?;
                    match field.as_str() {
                        "purpose" => purpose = Some(value),
                        "emit" => emit = Some(value),
                        _ => actions = Some(value),
                    }
                }
                "resource" => {
                    let name = self.word()?;
                    self.keyword("table")?;
                    let table = self.string()?;
                    self.punct(';')?;
                    resources.push(TargetResource {
                        name,
                        table,
                        location: at,
                    });
                }
                "action" => {
                    let name = self.word()?;
                    let parameters = self.parameters()?;
                    let returns = self.returns()?;
                    self.punct('{')?;
                    self.keyword("bind")?;
                    self.keyword("java")?;
                    let binding = self.string()?;
                    self.punct(';')?;
                    self.keyword("effects")?;
                    let effects = self.effects()?;
                    self.punct('}')?;
                    leaves.push(Leaf {
                        name,
                        parameters,
                        returns,
                        binding,
                        effects,
                        location: at,
                    });
                }
                "operation" => {
                    let name = self.word()?;
                    let parameters = self.parameters()?;
                    let returns = self.returns()?;
                    self.punct('{')?;
                    self.keyword("effects")?;
                    let effects = self.effects()?;
                    let no_effect_on_rejection =
                        if self.kind() == &Kind::Word("no_effect_on_rejection".into()) {
                            self.take();
                            self.effects()?
                        } else {
                            vec![]
                        };
                    let mut body = Vec::new();
                    while !self.eat('}') {
                        body.push(self.statement(0)?);
                    }
                    operations.push(Operation {
                        name,
                        parameters,
                        returns,
                        effects,
                        no_effect_on_rejection,
                        body,
                        location: at,
                    });
                }
                _ => return Err(self.fail(format!("Unknown workflow declaration '{field}'"))),
            }
        }
        if self.kind() != &Kind::End {
            return Err(self.fail("Unexpected content after workflow"));
        }
        Ok(Workflow {
            path: path.into(),
            feature,
            purpose: purpose.ok_or_else(|| self.fail("Workflow requires purpose"))?,
            emit: emit.ok_or_else(|| self.fail("Workflow requires emit java"))?,
            actions: actions.ok_or_else(|| self.fail("Workflow requires actions java"))?,
            resources,
            leaves,
            operations,
            location,
        })
    }
}
pub fn parse(path: &str, source: &str) -> Result<Workflow, Vec<Diagnostic>> {
    if source.len() > 2_000_000 {
        return Err(vec![error(
            &Location {
                path: path.into(),
                line: 1,
                column: 1,
            },
            "WORKFLOW_PARSE",
            "Workflow exceeds 2 MB",
        )]);
    }
    let tokens = target::tokenize(path, source).map_err(|mut e| {
        e.code = "WORKFLOW_PARSE".into();
        vec![e]
    })?;
    Parser { tokens, index: 0 }
        .workflow(path)
        .map_err(|e| vec![e])
}
fn identifier(s: &str) -> bool {
    let mut cs = s.chars();
    cs.next()
        .is_some_and(|c| c.is_ascii_alphabetic() || c == '_')
        && cs.all(|c| c.is_ascii_alphanumeric() || c == '_')
        && ![
            "_",
            "abstract",
            "assert",
            "boolean",
            "break",
            "byte",
            "case",
            "catch",
            "char",
            "class",
            "const",
            "continue",
            "default",
            "do",
            "double",
            "else",
            "enum",
            "extends",
            "final",
            "finally",
            "float",
            "for",
            "goto",
            "if",
            "implements",
            "import",
            "instanceof",
            "int",
            "interface",
            "long",
            "native",
            "new",
            "package",
            "private",
            "protected",
            "public",
            "return",
            "short",
            "static",
            "strictfp",
            "super",
            "switch",
            "synchronized",
            "this",
            "throw",
            "throws",
            "transient",
            "try",
            "void",
            "volatile",
            "while",
            "true",
            "false",
            "null",
            "var",
            "yield",
            "record",
            "sealed",
            "permits",
        ]
        .contains(&s)
}
fn class_name(s: &str) -> bool {
    s.contains('.') && s.split('.').all(identifier)
}
fn normal(s: &str) -> String {
    s.chars().filter(|c| !c.is_whitespace()).collect()
}
fn check_parameters(
    ps: &[TargetParameter],
    at: &Location,
    errors: &mut Vec<Diagnostic>,
) -> BTreeMap<String, String> {
    let mut env = BTreeMap::new();
    for p in ps {
        if !identifier(&p.name) || env.insert(p.name.clone(), normal(&p.native_type)).is_some() {
            errors.push(error(
                at,
                "WORKFLOW_NAME",
                format!("Invalid or duplicate parameter {}", p.name),
            ));
        }
        if let Err(e) = target::native_type(&p.native_type, false) {
            errors.push(error(at, "WORKFLOW_TYPE", e));
        }
    }
    env
}
fn check_effects(
    effects: &[ResourceEffect],
    resources: &BTreeSet<&String>,
    at: &Location,
    errors: &mut Vec<Diagnostic>,
) {
    let mut seen = BTreeSet::new();
    for effect in effects {
        if !matches!(effect.action.as_str(), "read" | "write")
            || !resources.contains(&effect.resource)
            || !seen.insert(effect)
        {
            errors.push(error(
                at,
                "WORKFLOW_EFFECT",
                format!(
                    "Invalid, duplicate, or undeclared effect {} {}",
                    effect.action, effect.resource
                ),
            ));
        }
    }
}
fn value_type(
    value: &Value,
    env: &BTreeMap<String, String>,
    at: &Location,
    errors: &mut Vec<Diagnostic>,
) -> String {
    match value {
        Value::Text(_) => "java.lang.String".into(),
        Value::Bool(_) => "boolean".into(),
        Value::Ref(name) => env.get(name).cloned().unwrap_or_else(|| {
            errors.push(error(
                at,
                "WORKFLOW_VALUE",
                format!("Unknown value {name}; branch-local values do not escape their block"),
            ));
            "<unknown>".into()
        }),
    }
}
fn check_call(
    call: &Call,
    env: &BTreeMap<String, String>,
    workflow: &Workflow,
    op: &Operation,
    effects: &mut BTreeSet<ResourceEffect>,
    at: &Location,
    errors: &mut Vec<Diagnostic>,
) -> String {
    let Some(action) = workflow.leaves.iter().find(|a| a.name == call.action) else {
        errors.push(error(
            at,
            "WORKFLOW_ACTION",
            format!("Unknown action {}", call.action),
        ));
        return "<unknown>".into();
    };
    let actual: Vec<_> = call
        .arguments
        .iter()
        .map(|v| value_type(v, env, at, errors))
        .collect();
    let expected: Vec<_> = action
        .parameters
        .iter()
        .map(|p| normal(&p.native_type))
        .collect();
    if actual != expected {
        errors.push(error(
            at,
            "WORKFLOW_ARGUMENTS",
            format!(
                "{} expects ({}) but received ({})",
                call.action,
                expected.join(", "),
                actual.join(", ")
            ),
        ));
    }
    for effect in &action.effects {
        effects.insert(effect.clone());
        if !op.effects.contains(effect) {
            errors.push(error(
                at,
                "WORKFLOW_EFFECT",
                format!(
                    "{} may perform {} {}, outside operation {} permissions",
                    call.action, effect.action, effect.resource, op.name
                ),
            ));
        }
    }
    normal(&action.returns)
}
/// Returns effects for paths which fall through. Terminal paths never rejoin.
fn check_block(
    body: &[Statement],
    mut env: BTreeMap<String, String>,
    mut effects: BTreeSet<ResourceEffect>,
    workflow: &Workflow,
    op: &Operation,
    errors: &mut Vec<Diagnostic>,
) -> Option<BTreeSet<ResourceEffect>> {
    let mut alive = true;
    for statement in body {
        let at = match statement {
            Statement::Let { location, .. }
            | Statement::Do { location, .. }
            | Statement::If { location, .. }
            | Statement::Return { location, .. }
            | Statement::Reject { location, .. } => location,
        };
        if !alive {
            errors.push(error(
                at,
                "WORKFLOW_UNREACHABLE",
                "Statement follows a terminal return/reject",
            ));
            break;
        }
        match statement {
            Statement::Let { name, call, .. } => {
                let ty = check_call(call, &env, workflow, op, &mut effects, at, errors);
                if ty == "void" {
                    errors.push(error(
                        at,
                        "WORKFLOW_TYPE",
                        "A void action must use 'do call'",
                    ));
                }
                if !identifier(name) || env.contains_key(name) {
                    errors.push(error(
                        at,
                        "WORKFLOW_BINDING",
                        format!("Invalid or repeated immutable binding {name}"),
                    ));
                } else {
                    env.insert(name.clone(), ty);
                }
            }
            Statement::Do { call, .. } => {
                if check_call(call, &env, workflow, op, &mut effects, at, errors) != "void" {
                    errors.push(error(
                        at,
                        "WORKFLOW_TYPE",
                        "Use let for an action that returns a value",
                    ));
                }
            }
            Statement::If {
                condition, yes, no, ..
            } => {
                if value_type(condition, &env, at, errors) != "boolean" {
                    errors.push(error(
                        at,
                        "WORKFLOW_TYPE",
                        "An if condition must have native boolean type",
                    ));
                }
                let a = check_block(yes, env.clone(), effects.clone(), workflow, op, errors);
                let b = check_block(no, env.clone(), effects.clone(), workflow, op, errors);
                match (a, b) {
                    (None, None) => alive = false,
                    (Some(a), None) | (None, Some(a)) => effects = a,
                    (Some(mut a), Some(b)) => {
                        a.extend(b);
                        effects = a;
                    }
                }
            }
            Statement::Return { value, .. } => {
                if value_type(value, &env, at, errors) != normal(&op.returns) {
                    errors.push(error(
                        at,
                        "WORKFLOW_TYPE",
                        format!("Return type must be {}", op.returns),
                    ));
                }
                alive = false;
            }
            Statement::Reject { .. } => {
                for effect in &op.no_effect_on_rejection {
                    if effects.contains(effect) {
                        let message = format!(
                            "Business rejection in {} may follow {} {}; move the effect after every rejecting validation",
                            op.name, effect.action, effect.resource
                        );
                        errors.push(error(at, "WORKFLOW_REJECTION_EFFECT", message));
                    }
                }
                alive = false;
            }
        }
    }
    alive.then_some(effects)
}
pub fn lint(workflow: &Workflow) -> Vec<Diagnostic> {
    let mut errors = Vec::new();
    let at = &workflow.location;
    if !workflow.feature.split('.').all(identifier) || workflow.purpose.trim().is_empty() {
        errors.push(error(
            at,
            "WORKFLOW_FEATURE",
            "Feature name and nonempty purpose are required",
        ));
    }
    if !class_name(&workflow.emit)
        || !class_name(&workflow.actions)
        || workflow.emit == workflow.actions
    {
        errors.push(error(
            at,
            "WORKFLOW_CLASS",
            "emit/actions must name distinct fully qualified Java classes",
        ));
    }
    if workflow.leaves.is_empty() || workflow.operations.is_empty() {
        errors.push(error(
            at,
            "WORKFLOW_EMPTY",
            "Workflow requires actions and operations",
        ));
    }
    let mut resources = BTreeSet::new();
    let mut tables = Vec::new();
    for resource in &workflow.resources {
        let table = resource.table.trim().to_ascii_lowercase();
        if !identifier(&resource.name)
            || !resources.insert(&resource.name)
            || table.split('.').count() > 2
            || !table.split('.').all(identifier)
            || tables
                .iter()
                .any(|old: &String| target::tables_may_alias(old, &table))
        {
            errors.push(error(
                &resource.location,
                "WORKFLOW_RESOURCE",
                "Invalid, duplicate, or ambiguous resource/table mapping",
            ));
        }
        tables.push(table);
    }
    let mut names = BTreeSet::new();
    for action in &workflow.leaves {
        let at = &action.location;
        if !identifier(&action.name) || !names.insert(&action.name) {
            errors.push(error(
                at,
                "WORKFLOW_NAME",
                "Invalid or duplicate action name",
            ));
        }
        check_parameters(&action.parameters, at, &mut errors);
        if let Err(e) = target::native_type(&action.returns, true) {
            errors.push(error(at, "WORKFLOW_TYPE", e));
        }
        let expected: Vec<_> = action
            .parameters
            .iter()
            .filter_map(|p| target::native_type(&p.native_type, false).ok())
            .collect();
        match target::binding_parts(&action.binding) {
            Some((owner, method, parameters))
                if owner == workflow.actions && identifier(method) && parameters == expected.join(",") => {}
            _ => errors.push(error(at, "WORKFLOW_BINDING",
                "Action binding must name a method on the actions class with the declared erased parameter types")),
        }
        check_effects(&action.effects, &resources, at, &mut errors);
    }
    names.clear();
    for op in &workflow.operations {
        if !identifier(&op.name)
            || !names.insert(&op.name)
            || op.name == workflow.emit.rsplit('.').next().unwrap_or("")
        {
            errors.push(error(
                &op.location,
                "WORKFLOW_NAME",
                "Invalid or duplicate operation name",
            ));
        }
        let env = check_parameters(&op.parameters, &op.location, &mut errors);
        if let Err(e) = target::native_type(&op.returns, false) {
            errors.push(error(&op.location, "WORKFLOW_TYPE", e));
        }
        check_effects(&op.effects, &resources, &op.location, &mut errors);
        check_effects(
            &op.no_effect_on_rejection,
            &resources,
            &op.location,
            &mut errors,
        );
        if check_block(&op.body, env, BTreeSet::new(), workflow, op, &mut errors).is_some() {
            errors.push(error(
                &op.location,
                "WORKFLOW_RETURN",
                "Every workflow path must return a value or reject",
            ));
        }
    }
    errors
}

/// Compare declared leaf bounds to attributed source. Empty effects never mean general Java purity.
pub fn check_leaves(workflow: &Workflow, program: &DerivedProgram) -> Vec<Diagnostic> {
    let mut errors = Vec::new();
    let at = &workflow.location;
    let Some(inventory) = program.inventory.as_ref().filter(|i| i.version == 2) else {
        return vec![error(
            at,
            "WORKFLOW_INVENTORY",
            "Rebuild the Java analyzer: workflow checks require inventory version 2",
        )];
    };
    // Their constructors define the lowering's exit semantics. An application
    // replacement could itself throw Rejected from Failed after a write, even
    // with an empty modeled effect set, so analyzing its effects is insufficient.
    if inventory.classes.iter().any(|class| {
        matches!(
            class.name.as_str(),
            "dev.vitrifi.workflow.Rejected" | "dev.vitrifi.workflow.Failed"
        )
    }) {
        return vec![error(
            at,
            "WORKFLOW_RUNTIME_SHADOW",
            "Application sources must not replace the workflow runtime outcome classes",
        )];
    }
    let owners: Vec<_> = inventory
        .classes
        .iter()
        .filter(|c| c.name == workflow.actions)
        .collect();
    if owners.len() != 1 {
        return vec![error(
            at,
            "WORKFLOW_ACTION_CLASS",
            "Actions must resolve to one source class",
        )];
    }
    for gap in &owners[0].unsupported_api {
        errors.push(error(at, "WORKFLOW_API_GAP", gap));
    }
    for resource in &workflow.resources {
        let table = resource.table.trim().to_ascii_lowercase();
        let matches: Vec<_> = inventory
            .resources
            .iter()
            .filter(|r| r.resource == resource.name || target::tables_may_alias(&r.table, &table))
            .collect();
        if matches.is_empty()
            || matches
                .iter()
                .any(|r| r.resource != resource.name || r.table != table)
        {
            errors.push(error(
                &resource.location,
                "WORKFLOW_RESOURCE",
                format!(
                    "Source mapping does not uniquely agree with {} = {table}",
                    resource.name
                ),
            ));
        }
    }
    let mut selected = BTreeSet::new();
    // Check actual emitted call dispatch too: a declared action class alone does
    // not establish which Spring bean will receive the generated invocation.
    for operation in &workflow.operations {
        let parameters = operation
            .parameters
            .iter()
            .map(|p| target::native_type(&p.native_type, false).unwrap())
            .collect::<Vec<_>>()
            .join(",");
        let symbol = format!("{}.{}({parameters})", workflow.emit, operation.name);
        let Some(actual) = program
            .operations
            .values()
            .find(|o| o.source.symbol == symbol)
        else {
            errors.push(error(
                &operation.location,
                "WORKFLOW_EMISSION",
                format!("Missing attributed generated method {symbol}"),
            ));
            continue;
        };
        selected.insert(actual.source.id.clone());
        for gap in &actual.reachable_unknowns {
            errors.push(error(
                &operation.location,
                "WORKFLOW_DISPATCH",
                format!(
                    "Generated operation {}: {} ({})",
                    operation.name, gap.expression, gap.reason
                ),
            ));
        }
        for call in &actual.source.calls {
            if call.expression.starts_with("$actions.") {
                let resolved = call
                    .target
                    .as_ref()
                    .and_then(|id| program.operations.get(id));
                if !resolved.is_some_and(|callee| {
                    workflow
                        .leaves
                        .iter()
                        .any(|leaf| leaf.binding == callee.source.symbol)
                }) {
                    errors.push(error(
                        &operation.location,
                        "WORKFLOW_DISPATCH",
                        format!(
                            "{} must resolve to a declared source action",
                            call.expression
                        ),
                    ));
                }
            }
        }
        for effect in &actual.effective_effects {
            if !operation.effects.contains(effect) {
                errors.push(error(
                    &operation.location,
                    "WORKFLOW_EFFECT",
                    format!(
                        "Generated operation {} reaches undeclared {} {}",
                        operation.name, effect.action, effect.resource
                    ),
                ));
            }
        }
    }
    for action in &workflow.leaves {
        let found: Vec<_> = program
            .operations
            .values()
            .filter(|o| o.source.symbol == action.binding && o.source.language == "java")
            .collect();
        if found.len() != 1 || !owners[0].public_methods.contains(&action.binding) {
            errors.push(error(
                &action.location,
                "WORKFLOW_ACTION_BINDING",
                format!("Expected one public source action {}", action.binding),
            ));
            continue;
        }
        let actual = found[0];
        let a: Vec<_> = actual
            .source
            .parameters
            .iter()
            .map(|p| normal(&p.annotation))
            .collect();
        let b: Vec<_> = action
            .parameters
            .iter()
            .map(|p| normal(&p.native_type))
            .collect();
        if a != b || normal(&actual.source.returns) != normal(&action.returns) {
            errors.push(error(
                &action.location,
                "WORKFLOW_NATIVE_TYPE",
                format!("Native action signature drift for {}", action.name),
            ));
        }
        for effect in &actual.effective_effects {
            if !action.effects.contains(effect) {
                errors.push(error(
                    &action.location,
                    "WORKFLOW_LEAF_EFFECT",
                    format!(
                        "{} reaches undeclared {} {}",
                        action.name, effect.action, effect.resource
                    ),
                ));
            }
        }
        for gap in &actual.reachable_unknowns {
            errors.push(error(
                &action.location,
                "WORKFLOW_ANALYSIS_GAP",
                format!("{}: {} ({})", action.name, gap.expression, gap.reason),
            ));
        }
        let mut queue = vec![actual.source.id.clone()];
        while let Some(id) = queue.pop() {
            if selected.insert(id.clone()) {
                if let Some(o) = program.operations.get(&id) {
                    queue.extend(o.callees.iter().cloned());
                }
            }
        }
    }
    errors.extend(crate::derived::scoped_diagnostics(program, &selected));
    errors
}

fn quoted(s: &str) -> String {
    serde_json::to_string(s).unwrap()
}
fn java_value(v: &Value) -> String {
    match v {
        Value::Ref(s) => s.clone(),
        Value::Text(s) => quoted(s),
        Value::Bool(b) => b.to_string(),
    }
}
fn emit_block(body: &[Statement], workflow: &Workflow, indent: usize, output: &mut String) {
    let pad = "    ".repeat(indent);
    for statement in body {
        match statement {
            Statement::Let { call, .. } | Statement::Do { call, .. } => {
                let leaf = workflow
                    .leaves
                    .iter()
                    .find(|a| a.name == call.action)
                    .unwrap();
                let method = target::binding_parts(&leaf.binding).unwrap().1;
                if let Statement::Let { name, .. } = statement {
                    output.push_str(&format!("{pad}final {} {name};\n", leaf.returns));
                }
                output.push_str(&format!("{pad}try {{\n{pad}    "));
                if let Statement::Let { name, .. } = statement {
                    output.push_str(&format!("{name} = "));
                }
                let arguments = call
                    .arguments
                    .iter()
                    .map(java_value)
                    .collect::<Vec<_>>()
                    .join(", ");
                output.push_str(&format!(
                    "$actions.{method}({arguments});\n{pad}}} catch (Exception $failure) {{\n"
                ));
                output.push_str(&format!(
                    "{pad}    throw new dev.vitrifi.workflow.Failed({}, $failure);\n{pad}}}\n",
                    quoted(&call.action)
                ));
            }
            Statement::If {
                condition, yes, no, ..
            } => {
                output.push_str(&format!("{pad}if ({}) {{\n", java_value(condition)));
                emit_block(yes, workflow, indent + 1, output);
                output.push_str(&format!("{pad}}} else {{\n"));
                emit_block(no, workflow, indent + 1, output);
                output.push_str(&format!("{pad}}}\n"));
            }
            Statement::Return { value, .. } => {
                output.push_str(&format!("{pad}return {};\n", java_value(value)))
            }
            Statement::Reject { message, .. } => output.push_str(&format!(
                "{pad}throw new dev.vitrifi.workflow.Rejected({});\n",
                quoted(message)
            )),
        }
    }
}
pub fn render(workflow: &Workflow) -> Result<String, Vec<Diagnostic>> {
    let errors = lint(workflow);
    if !errors.is_empty() {
        return Err(errors);
    }
    let (package, class) = workflow.emit.rsplit_once('.').unwrap();
    let mut output = format!(
        "{GENERATED_MARKER}\n// Workflow: {}\n",
        quoted(&workflow.path)
    );
    output.push_str(&format!(
        "// Semantics: {SEMANTICS}; edit the workflow and rebuild.\npackage {package};\n\n"
    ));
    output.push_str("@org.springframework.stereotype.Service\n");
    output.push_str(&format!(
        "@dev.vitrifi.api.Feature(value = {}, purpose = {})\n",
        quoted(&workflow.feature),
        quoted(&workflow.purpose)
    ));
    output.push_str(&format!(
        "public class {class} {{\n    private final {} $actions;\n\n",
        workflow.actions
    ));
    output.push_str(&format!(
        "    public {class}({} $actions) {{\n        this.$actions = $actions;\n    }}\n",
        workflow.actions
    ));
    for op in &workflow.operations {
        output.push('\n');
        for resource in &workflow.resources {
            for action in ["read", "write"] {
                if !op.effects.contains(&ResourceEffect {
                    action: action.into(),
                    resource: resource.name.clone(),
                }) {
                    output.push_str(&format!(
                        "    @dev.vitrifi.api.Forbid(action = {}, resource = {})\n",
                        quoted(action),
                        quoted(&resource.name)
                    ));
                }
            }
        }
        for effect in &op.no_effect_on_rejection {
            output.push_str(&format!(
                "    @dev.vitrifi.api.NoEffectOnRejection(action = {}, resource = {})\n",
                quoted(&effect.action),
                quoted(&effect.resource)
            ));
        }
        output.push_str(&format!(
            "    public {} {}({}) {{\n",
            op.returns,
            op.name,
            op.parameters
                .iter()
                .map(|p| format!("{} {}", p.native_type, p.name))
                .collect::<Vec<_>>()
                .join(", ")
        ));
        emit_block(&op.body, workflow, 2, &mut output);
        output.push_str("    }\n");
    }
    output.push_str("}\n");
    Ok(output)
}

#[cfg(test)]
mod tests {
    use super::*;
    const EXAMPLE: &str = include_str!("../examples/workflow-checkout/src/main/java/dev/vitrifi/example/checkout/Checkout.Discounts.workflow.vitrifi");
    fn errors(source: &str) -> Vec<Diagnostic> {
        match parse("Checkout.workflow.vitrifi", source) {
            Ok(w) => lint(&w),
            Err(e) => e,
        }
    }
    fn has(source: &str, code: &str) {
        let errors = errors(source);
        assert!(
            errors.iter().any(|d| d.code == code),
            "expected {code}, got {errors:?}"
        );
    }
    #[test]
    fn checkout_and_deterministic_generation() {
        let workflow = parse("Checkout.workflow.vitrifi", EXAMPLE).unwrap();
        assert!(lint(&workflow).is_empty());
        let java = render(&workflow).unwrap();
        assert_eq!(java, render(&workflow).unwrap());
        assert!(java.contains("final dev.vitrifi.example.checkout.Cart cart;"));
        assert!(java.contains("throw new dev.vitrifi.workflow.Failed(\"save\", $failure)"));
        assert!(java.contains("@dev.vitrifi.api.NoEffectOnRejection"));
    }
    #[test]
    fn write_before_rejection_fails_even_if_result_is_unused() {
        let source = EXAMPLE.replace(
            "let owner =",
            "let early = call save(cart, code);\nlet owner =",
        );
        has(&source, "WORKFLOW_REJECTION_EFFECT");
    }
    #[test]
    fn terminal_accepted_branch_does_not_pollute_rejected_branch() {
        let mut workflow = parse("X.workflow.vitrifi", EXAMPLE).unwrap();
        let body = "{ let cart = call load(cartId); let owner = call owns(actorId, cart); if owner { let receipt = call save(cart, code); return receipt; } else { reject \"not owner\"; } }";
        let mut parser = Parser {
            tokens: target::tokenize("test", body).unwrap(),
            index: 0,
        };
        workflow.operations[0].body = parser.block(0).unwrap();
        assert!(lint(&workflow).is_empty());
    }
    #[test]
    fn continuing_branch_effects_reach_later_reject() {
        let source = EXAMPLE.replace(
            "if owner {",
            "if owner { let early = call save(cart, code);",
        );
        has(&source, "WORKFLOW_REJECTION_EFFECT");
    }
    #[test]
    fn types_arguments_and_conditions_are_checked() {
        for (before, after, code) in [
            (
                "call owns(actorId, cart)",
                "call owns(cart, actorId)",
                "WORKFLOW_ARGUMENTS",
            ),
            ("if owner {", "if cart {", "WORKFLOW_TYPE"),
            ("return receipt;", "return cart;", "WORKFLOW_TYPE"),
            (
                "call load(cartId)",
                "call missing(cartId)",
                "WORKFLOW_ACTION",
            ),
            ("return receipt;", "return missing;", "WORKFLOW_VALUE"),
            ("let owner =", "let cart =", "WORKFLOW_BINDING"),
            ("return receipt;", "", "WORKFLOW_RETURN"),
            (
                "return receipt;",
                "return receipt; reject \"late\";",
                "WORKFLOW_UNREACHABLE",
            ),
            (
                "if owner {",
                "if owner { let local = call load(cartId);",
                "WORKFLOW_VALUE",
            ),
        ] {
            let mut source = EXAMPLE.replace(before, after);
            if code == "WORKFLOW_VALUE" && before == "if owner {" {
                source = source.replace("return receipt;", "return local;");
            }
            has(&source, code);
        }
    }
    #[test]
    fn effect_bounds_names_and_native_bindings_are_checked() {
        has(
            &EXAMPLE.replace("effects [read Carts, write Carts]", "effects [read Carts]"),
            "WORKFLOW_EFFECT",
        );
        has(
            &EXAMPLE.replace("let owner =", "let class ="),
            "WORKFLOW_BINDING",
        );
        has(
            &EXAMPLE.replace(
                "CheckoutActions.load(java.lang.String)",
                "OtherActions.load(java.lang.String)",
            ),
            "WORKFLOW_BINDING",
        );
        has(
            &EXAMPLE.replace(
                "resource Carts table \"carts\";",
                "resource Carts table \"carts\"; resource Other table \"public.carts\";",
            ),
            "WORKFLOW_RESOURCE",
        );
        has(
            &EXAMPLE.replace(
                "actions java \"dev.vitrifi.example.checkout.CheckoutActions\"",
                "actions java \"../escape\"",
            ),
            "WORKFLOW_CLASS",
        );
    }
    #[test]
    fn bounded_parser_rejects_incomplete_and_unsupported_syntax() {
        for source in [
            "workflow",
            "workflow feature X {",
            "workflow feature X { operation f(",
            "workflow feature X { purpose",
        ] {
            assert!(parse("bad", source).is_err());
        }
        has(
            &EXAMPLE.replace("return receipt;", "while true { return receipt; }"),
            "WORKFLOW_PARSE",
        );
        has(
            &EXAMPLE.replace(
                "return receipt;",
                &("if true {".repeat(70)
                    + "return receipt;"
                    + &"} else { reject \"x\"; }".repeat(70)),
            ),
            "WORKFLOW_PARSE",
        );
    }
    #[test]
    fn void_leaves_use_do_and_operations_return_values() {
        let source = EXAMPLE.replace("action save(cart: \"dev.vitrifi.example.checkout.Cart\", code: \"java.lang.String\") -> \"dev.vitrifi.example.checkout.Receipt\"", "action save(cart: \"dev.vitrifi.example.checkout.Cart\", code: \"java.lang.String\") -> \"void\"");
        has(&source, "WORKFLOW_TYPE");
        has(
            &EXAMPLE.replace("let receipt = call save", "do call save"),
            "WORKFLOW_TYPE",
        );
    }
}
